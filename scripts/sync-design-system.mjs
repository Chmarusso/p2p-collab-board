// Copies the desktop app's stylesheet (the <style> block in renderer/index.html)
// into the landing site's design system, so its app components render with the
// app's real CSS. Run it after changing renderer styles:
//
//   node scripts/sync-design-system.mjs
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import prettier from 'prettier'

const root = path.join(import.meta.dirname, '..')
const html = fs.readFileSync(path.join(root, 'renderer', 'index.html'), 'utf8')
const match = html.match(/<style>([\s\S]*?)<\/style>/)
if (!match) {
  console.error('No <style> block in renderer/index.html')
  process.exit(1)
}

const css = match[1]
  .split('\n')
  .map((line) => line.replace(/^ {6}/, ''))
  .join('\n')
  .trim()

const out = path.join(root, 'apps', 'landing', 'design-system', 'app.css')
fs.mkdirSync(path.dirname(out), { recursive: true })
const header =
  "/* Generated by scripts/sync-design-system.mjs from renderer/index.html. Don't edit. */"
const options = await prettier.resolveConfig(out)
fs.writeFileSync(out, await prettier.format(`${header}\n${css}\n`, { ...options, filepath: out }))
console.log(`Wrote ${path.relative(root, out)}`)
